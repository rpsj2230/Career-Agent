// Embeds the SQL migration files into src/lib/migrations.ts so the System page can show them without reading
// the filesystem at runtime. Run: npm run gen:migrations. A test fails if the two ever drift apart.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const items = files.map((f) => ({ id: f.replace(/\.sql$/, ""), sql: readFileSync(`${dir}/${f}`, "utf8") }));
const out = `// GENERATED by scripts/gen-migrations.mjs from supabase/migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS: { id: string; sql: string }[] = ${JSON.stringify(items, null, 2)};\n`;
writeFileSync("src/lib/migrations.ts", out);
console.log(`embedded ${items.length} migration(s): ${items.map((i) => i.id).join(", ")}`);
